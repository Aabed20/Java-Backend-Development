package com.nit;

public class Calculation 
{
	
	public int add(int a, int b)
	{
		return a+b;
	}
	
	public int sub(int a,int b)
	{
		return a-b;
	}
	
	public int multiplication(int a, int b)
	{
		return a*b;
	}
	
	public int division(int a, int b)
	{
		return a/b;
	}
	
	public boolean isPositive(int number)
	{
		return number>0;
	}

}
